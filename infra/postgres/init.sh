#!/bin/sh
set -eu

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
CREATE ROLE migrator LOGIN CREATEDB PASSWORD '$MIGRATOR_PASSWORD';
CREATE ROLE app_core LOGIN PASSWORD '$APP_CORE_PASSWORD';
CREATE ROLE app_notifications LOGIN PASSWORD '$APP_NOTIFICATIONS_PASSWORD';

GRANT CREATE ON DATABASE "$POSTGRES_DB" TO migrator;
REVOKE ALL ON SCHEMA public FROM PUBLIC;

CREATE SCHEMA core AUTHORIZATION migrator;
CREATE SCHEMA notifications AUTHORIZATION migrator;

GRANT USAGE ON SCHEMA core TO app_core;
GRANT USAGE ON SCHEMA notifications TO app_notifications;

ALTER DEFAULT PRIVILEGES FOR ROLE migrator IN SCHEMA core
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app_core;
ALTER DEFAULT PRIVILEGES FOR ROLE migrator IN SCHEMA core
  GRANT USAGE, SELECT ON SEQUENCES TO app_core;
ALTER DEFAULT PRIVILEGES FOR ROLE migrator IN SCHEMA notifications
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app_notifications;
ALTER DEFAULT PRIVILEGES FOR ROLE migrator IN SCHEMA notifications
  GRANT USAGE, SELECT ON SEQUENCES TO app_notifications;
SQL
